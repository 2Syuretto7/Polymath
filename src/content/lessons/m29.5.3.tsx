      <Definition title="the Hilbert class field">
        <p>
          For a number field K, the <strong>Hilbert class field</strong> H is the largest abelian extension of K in which no
          prime ideal ramifies, including at the infinite places. Its Galois group over K is isomorphic to the class group of
          K, by the <strong>Artin map</strong>, which sends a prime P of K to its Frobenius element. So a prime of K splits
          completely in H exactly when it is principal, and <M>{"[H : K] = h_K"}</M>.
        </p>
      </Definition>

