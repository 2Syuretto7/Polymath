      <Definition title="one-parameter subgroups and exp">
        <p>
          A <strong>one-parameter subgroup</strong> is a Lie group homomorphism <M>{"\\varphi: \\mathbb{R} \\to G"}</M>.
          For each X in the Lie algebra <M>{"\\mathfrak{g} = T_eG"}</M> there is exactly one with{" "}
          <M>{"\\varphi'(0) = X"}</M>: the integral curve through e of the left-invariant field extending X. Define{" "}
          <M>{"\\exp X = \\varphi(1)"}</M>. For matrix groups,{" "}
          <M>{"\\exp X = \\sum_k X^k / k!"}</M>.
        </p>
      </Definition>

