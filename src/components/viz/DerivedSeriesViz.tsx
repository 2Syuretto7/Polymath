"use client";

import { useMemo, useState } from "react";
import { cycleString, generate, inverse } from "./permUtil";

type G = { label: string; gens: number[][]; names: string[] };
const GS: G[] = [
  { label: "S₃", gens: [[1, 0, 2], [1, 2, 0]], names: ["S₃", "A₃ ≅ C₃", "{1}"] },
  { label: "D₄", gens: [[1, 2, 3, 0], [0, 3, 2, 1]], names: ["D₄", "⟨r²⟩ ≅ C₂", "{1}"] },
  { label: "A₄", gens: [[1, 2, 0, 3], [1, 0, 3, 2]], names: ["A₄", "V₄", "{1}"] },
  { label: "S₄", gens: [[1, 0, 2, 3], [1, 2, 3, 0]], names: ["S₄", "A₄", "V₄", "{1}"] },
  { label: "A₅", gens: [[1, 2, 0, 3, 4], [1, 2, 3, 4, 0]], names: ["A₅"] },
  { label: "S₅", gens: [[1, 0, 2, 3, 4], [1, 2, 3, 4, 0]], names: ["S₅", "A₅"] },
];
const mul = (p: number[], q: number[]) => p.map((x) => q[x]); // p, then q
const comm = (a: number[], b: number[]) => mul(mul(mul(a, b), inverse(a)), inverse(b));

function derived(H: number[][]): number[][] {
  const m = new Map<string, number[]>();
  for (const a of H) for (const b of H) { const c = comm(a, b); m.set(c.join(), c); }
  return generate([...m.values()]);
}

/** The derived series of a small permutation group, computed by taking commutators until it stabilises. */
export function DerivedSeriesViz() {
  const [gi, setGi] = useState(3);
  const [k, setK] = useState(0);
  const g = GS[gi];
  const series = useMemo(() => {
    const s = [generate(g.gens)];
    for (;;) { const d = derived(s[s.length - 1]); if (d.length === s[s.length - 1].length) break; s.push(d); }
    return s;
  }, [g]);
  const solvable = series[series.length - 1].length === 1;
  const G0 = series[0];
  // a sample pair, chosen by a simple counter so that repeated clicks step through the group
  const a = G0[(7 * k + 3) % G0.length], b = G0[(11 * k + 5) % G0.length], c = comm(a, b);
  const W = 520, rowH = 64, H = series.length * rowH + (solvable ? 0 : 40) + 10;
  const name = (i: number) => g.names[i] ?? `order ${series[i].length}`;
  return (
    <figure className="viz">
      <div className="segmented" role="group" aria-label="Group">
        {GS.map((x, i) => <button key={x.label} type="button" aria-pressed={gi === i} className={gi === i ? "seg is-on" : "seg"} onClick={() => { setGi(i); setK(0); }}>{x.label}</button>)}
      </div>
      <svg viewBox={`0 0 ${W} ${H}`} role="img" aria-label="The derived series, each term the commutator subgroup of the one before" style={{ width: "100%", maxWidth: 560, display: "block", margin: "8px auto" }}>
        {series.map((s, i) => {
          const y = 10 + i * rowH, w = 70 + 300 * (Math.log(s.length + 1) / Math.log(121));
          return (
            <g key={i}>
              <rect x={W / 2 - w / 2} y={y} width={w} height={34} rx={6} style={{ fill: i === series.length - 1 && !solvable ? "var(--danger-soft)" : "var(--bg)", stroke: "var(--accent)", strokeWidth: 1.5 }} />
              <text x={W / 2} y={y + 22} textAnchor="middle" style={{ fill: "var(--text)", fontSize: 14 }}>{`G${i === 0 ? "" : `⁽${"¹²³⁴"[i - 1]}⁾`} = ${name(i)}, order ${s.length}`}</text>
              {i > 0 && (
                <text x={W / 2 + 10} y={y - 11} style={{ fill: "var(--text-muted)", fontSize: 12 }}>
                  {`quotient of order ${series[i - 1].length / s.length}, abelian`}
                </text>
              )}
              {i > 0 && <line x1={W / 2} y1={y - 30} x2={W / 2} y2={y - 2} style={{ stroke: "var(--border)", strokeWidth: 1.5 }} />}
            </g>
          );
        })}
        {!solvable && (
          <text x={W / 2} y={H - 14} textAnchor="middle" style={{ fill: "var(--text)", fontSize: 13 }}>
            the commutators of A₅ generate all of A₅: the series is stuck
          </text>
        )}
      </svg>
      <div className="viz-controls">
        <button type="button" className="btn" onClick={() => setK(k + 1)}>Another commutator</button>
      </div>
      <div className="mono" style={{ display: "grid", gap: 4, fontSize: 14, marginTop: 6 }}>
        <div>a = {cycleString(a)}, b = {cycleString(b)}</div>
        <div>[a, b] = a b a⁻¹ b⁻¹ = {cycleString(c)}, which lies in G⁽¹⁾ = {name(Math.min(1, series.length - 1))}</div>
        <div>solvable: <strong>{solvable ? "yes, the series reaches {1}" : "no, it never reaches {1}"}</strong></div>
      </div>
      <figcaption className="viz-caption">
        Each term is the commutator subgroup of the one before: the subgroup generated by all a b a⁻¹ b⁻¹. It is normal, and the
        quotient is abelian. A group is solvable when the series reaches the trivial group. Here permutations are composed left
        to right, and cycles are written with the points labelled from 1.
      </figcaption>
    </figure>
  );
}
