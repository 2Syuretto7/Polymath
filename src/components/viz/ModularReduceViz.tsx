"use client";

import { useState } from "react";

/** Reduce τ to the standard fundamental domain by translations T: τ ↦ τ + k and the inversion S: τ ↦ −1/τ. */
export function reduceTau(x: number, y: number) {
  const path: [number, number][] = [[x, y]];
  const word: string[] = [];
  let inversions = 0;
  for (let k = 0; k < 60; k++) {
    const shift = Math.floor(x + 0.5);
    if (shift !== 0) { x -= shift; word.push(shift > 0 ? `T to the −${shift}` : `T to the ${-shift}`); path.push([x, y]); }
    const r2 = x * x + y * y;
    if (r2 < 1 - 1e-12) { x = -x / r2; y = y / r2; inversions++; word.push("S"); path.push([x, y]); }
    else break;
  }
  return { x, y, path, word, inversions };
}

/** Moving a point of the upper half-plane into the fundamental domain of SL(2, ℤ). */
export function ModularReduceViz() {
  const [x0, setX] = useState(0.37);
  const [y0, setY] = useState(0.08);
  const r = reduceTau(x0, y0);
  const px = (x: number) => 270 + x * 85, py = (y: number) => 230 - y * 105;
  const arc = (cx: number) => `M${px(cx - 1)},${py(0)} A85,105 0 0 1 ${px(cx + 1)},${py(0)}`;
  const top = 2.15;
  const fd = `M${px(-0.5)},${py(top)} L${px(-0.5)},${py(Math.sqrt(0.75))} A85,105 0 0 1 ${px(0.5)},${py(Math.sqrt(0.75))} L${px(0.5)},${py(top)} Z`;
  const clip = (y: number) => Math.min(y, top);
  const f = (v: number) => v.toFixed(3).replace("-", "−");
  return (
    <figure className="viz">
      <div className="viz-controls">
        <label>Re τ = {x0.toFixed(2).replace("-", "−")} <input type="range" min={-2} max={2} step={0.01} value={x0} onChange={(e) => setX(Number(e.target.value))} aria-label="real part" /></label>
        <label>Im τ = {y0.toFixed(2)} <input type="range" min={0.02} max={1.5} step={0.01} value={y0} onChange={(e) => setY(Number(e.target.value))} aria-label="imaginary part" /></label>
      </div>
      <svg viewBox="0 0 540 250" role="img" aria-label="Reduction of a point to the fundamental domain" style={{ width: "100%", display: "block", marginTop: 8 }}>
        <path d={fd} style={{ fill: "var(--accent-soft)", stroke: "var(--accent)", strokeWidth: 1.5 }} />
        {[-3, -2, -1, 0, 1, 2, 3].map((c) => <path key={c} d={arc(c)} style={{ fill: "none", stroke: "var(--grid-line)" }} />)}
        {[-2.5, -1.5, -0.5, 0.5, 1.5, 2.5].map((c) => <line key={c} x1={px(c)} y1={py(0)} x2={px(c)} y2={py(top)} style={{ stroke: "var(--grid-line)" }} />)}
        <line x1={0} y1={py(0)} x2={540} y2={py(0)} style={{ stroke: "var(--border-strong)" }} />
        {[-3, -2, -1, 0, 1, 2, 3].map((c) => <text key={c} x={px(c)} y={py(0) + 14} textAnchor="middle" style={{ fill: "var(--text-muted)", fontSize: 10 }}>{String(c).replace("-", "−")}</text>)}
        <path d={r.path.map(([x, y], i) => `${i ? "L" : "M"}${px(x).toFixed(1)},${py(clip(y)).toFixed(1)}`).join("")} style={{ fill: "none", stroke: "var(--danger)", strokeDasharray: "4 3" }} />
        {r.path.map(([x, y], i) => (
          <circle key={i} cx={px(x)} cy={py(clip(y))} r={i === 0 || i === r.path.length - 1 ? 5 : 3} style={{ fill: i === r.path.length - 1 ? "var(--success)" : "var(--danger)" }} />
        ))}
      </svg>
      <p className="mono" style={{ fontSize: 13, fontWeight: 700 }}>
        Steps: {r.word.length ? r.word.join(", ") : "none, already reduced"}. Inversions S used: {r.inversions}. Result: {f(r.x)} + {f(r.y)}i{r.y > top ? " (above the picture)" : ""}.
      </p>
      <figcaption className="viz-caption">
        The modular group acts on the upper half-plane by τ ↦ (aτ + b)/(cτ + d). It is generated by T: τ ↦ τ + 1 and
        S: τ ↦ −1/τ. Translate τ into the strip |Re τ| ≤ ½, and invert whenever |τ| &lt; 1; each inversion raises Im τ,
        and the process ends in the shaded region, the fundamental domain.
      </figcaption>
    </figure>
  );
}
