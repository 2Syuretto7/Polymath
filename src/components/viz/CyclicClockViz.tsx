"use client";

import { useState } from "react";

const SUBD = "₀₁₂₃₄₅₆₇₈₉";
const sub = (m: number) => String(m).split("").map((c) => SUBD[Number(c)]).join("");
const rowsOf = (xs: number[], k: number) => Array.from({ length: Math.ceil(xs.length / k) }, (_, i) => xs.slice(i * k, i * k + k));
const gcd = (a: number, b: number): number => (b === 0 ? a : gcd(b, a % b));

/** Step around ℤₙ in jumps of g. The path closes after n/gcd(n, g) steps, and visits everything exactly when gcd(n, g) = 1. */
export function CyclicClockViz() {
  const [n, setN] = useState(12);
  const [g, setG] = useState(5);
  const gg = g % n;
  const d = gcd(n, gg);
  const ord = n / d;
  const phi = Array.from({ length: n }, (_, i) => i).filter((i) => gcd(n, i) === 1).length;
  const cx = 120, cy = 115, R = 92;
  const pos = (i: number) => { const a = Math.PI / 2 - (2 * Math.PI * i) / n; return [cx + R * Math.cos(a), cy - R * Math.sin(a)]; };
  const path = Array.from({ length: ord + 1 }, (_, j) => (j * gg) % n);
  const hit = new Set(path);

  return (
    <figure className="viz">
      <svg viewBox="0 0 520 230" role="img" aria-label="Multiples of g around a clock with n hours" style={{ width: "100%", display: "block" }}>
        <circle cx={cx} cy={cy} r={R} style={{ fill: "none", stroke: "var(--border)" }} />
        <polyline points={path.map((i) => pos(i).map((v) => v.toFixed(1)).join(",")).join(" ")} style={{ fill: "none", stroke: "var(--accent)", strokeWidth: 1.8 }} />
        {Array.from({ length: n }, (_, i) => {
          const [x, y] = pos(i);
          return <g key={i}><circle cx={x} cy={y} r={9} style={{ fill: hit.has(i) ? "var(--accent)" : "var(--bg)", stroke: hit.has(i) ? "var(--accent)" : "var(--border-strong)" }} />
            <text x={x} y={y + 3.5} textAnchor="middle" style={{ fontSize: 9, fill: hit.has(i) ? "var(--bg)" : "var(--text-muted)" }}>{i}</text></g>;
        })}
        <text x={260} y={40} style={{ fontSize: 12, fill: "var(--text-muted)" }}>the subgroup generated by {gg} in ℤ{sub(n)}</text>
        {hit.size === n
          ? <text x={260} y={66} className="mono" style={{ fontSize: 13, fill: "var(--text)" }}>all of ℤ{sub(n)}</text>
          : rowsOf([...hit].sort((a, b) => a - b), 6).map((r, i, all) => (
            <text key={i} x={260} y={66 + i * 20} className="mono" style={{ fontSize: 13, fill: "var(--text)" }}>{i === 0 ? "{" : "\u00a0"}{r.join(", ")}{i === all.length - 1 ? "}" : ","}</text>
          ))}
      </svg>
      <div className="viz-sliders">
        <label><span>n: <span className="mono">{n}</span></span>
          <input type="range" min={2} max={24} value={n} onChange={(ev) => { const m = Number(ev.target.value); setN(m); if (g >= m) setG(1); }} /></label>
        <label><span>g: <span className="mono">{gg}</span></span>
          <input type="range" min={0} max={n - 1} value={gg} onChange={(ev) => setG(Number(ev.target.value))} /></label>
      </div>
      <table className="table" style={{ marginTop: 8 }}>
        <tbody>
          <tr><td>gcd(n, g)</td><td className="mono">{d}</td></tr>
          <tr><td>order of g, which is n / gcd(n, g)</td><td className="mono">{ord}</td></tr>
          <tr><td>does g generate all of ℤₙ?</td><td>{d === 1 ? "yes" : "no"}</td></tr>
          <tr><td>number of generators of ℤₙ</td><td className="mono">{phi}</td></tr>
        </tbody>
      </table>
      <figcaption className="viz-caption">
        The multiples of g form the subgroup generated by g, and it is cyclic. Its size is n divided by gcd(n, g), and the subgroups of ℤₙ are exactly ⟨d⟩ for the divisors d of n.
      </figcaption>
    </figure>
  );
}
