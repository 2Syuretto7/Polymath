"use client";

import { useState } from "react";
import { isOneMod4 } from "./QuadIntegerViz";

export const REAL_DS = [2, 3, 5, 6, 7, 10, 11, 13, 14, 15];

/** The fundamental unit of ℚ(√d), d > 0, as (a + b√d)/q with q = 2 when d ≡ 1 (mod 4) and q = 1 otherwise, and its norm. */
export function fundamentalUnit(d: number) {
  const k = isOneMod4(d) ? 4 : 1;
  for (let b = 1; b < 100000; b++) for (const s of [-1, 1]) {
    const a2 = d * b * b + s * k;
    const a = Math.round(Math.sqrt(a2));
    if (a > 0 && a * a === a2) return { a, b, q: k === 4 ? 2 : 1, norm: s };
  }
  return { a: 1, b: 0, q: 1, norm: 1 };
}
/** The regulator log ε of a real quadratic field. */
export const regulator = (d: number) => { const u = fundamentalUnit(d); return Math.log((u.a + u.b * Math.sqrt(d)) / u.q); };

/** The units of a real quadratic field in the logarithmic embedding: a lattice on the line x + y = 0. */
export function UnitLogViz() {
  const [k, setK] = useState(4);
  const d = REAL_DS[k];
  const u = fundamentalUnit(d);
  const R = regulator(d);
  const S = 34, X0 = 270, Y0 = 125;
  const powers = Array.from({ length: 9 }, (_, i) => i - 4).filter((n) => Math.abs(n * R) <= 3.5);
  const eps = u.q === 2 ? `(${u.a} + ${u.b === 1 ? "" : u.b}√${d})/2` : `${u.a} + ${u.b === 1 ? "" : u.b}√${d}`;
  return (
    <figure className="viz">
      <div className="viz-controls">
        <label>d = {d} <input type="range" min={0} max={REAL_DS.length - 1} step={1} value={k} onChange={(e) => setK(Number(e.target.value))} aria-label="d" /></label>
      </div>
      <svg viewBox="0 0 540 250" role="img" aria-label="Units in the logarithmic embedding" style={{ width: "100%", display: "block", marginTop: 8 }}>
        <line x1={20} y1={Y0} x2={520} y2={Y0} style={{ stroke: "var(--grid-line)" }} />
        <line x1={X0} y1={5} x2={X0} y2={245} style={{ stroke: "var(--grid-line)" }} />
        <line x1={X0 - 3.5 * S} y1={Y0 - 3.5 * S} x2={X0 + 3.5 * S} y2={Y0 + 3.5 * S} style={{ stroke: "var(--border-strong)", strokeDasharray: "5 3" }} />
        <text x={X0 + 3.5 * S - 4} y={Y0 + 3.5 * S - 8} textAnchor="end" style={{ fill: "var(--text-muted)", fontSize: 10 }}>x + y = 0</text>
        {powers.map((n) => {
          const px = X0 + n * R * S, py = Y0 + n * R * S;
          return (
            <g key={n}>
              <circle cx={px} cy={py} r={n === 0 ? 4 : 6} style={{ fill: n === 1 ? "var(--success)" : n === 0 ? "var(--text)" : "var(--accent)" }} />
              <text x={px + 9} y={py - 6} style={{ fill: "var(--text-muted)", fontSize: 10 }}>{n === 0 ? "±1" : n === 1 ? "ε" : `ε to the ${n}`.replace("-", "−")}</text>
            </g>
          );
        })}
        <text x={516} y={Y0 - 6} textAnchor="end" style={{ fill: "var(--text-muted)", fontSize: 10 }}>log|σ₁(u)|</text>
        <text x={X0 + 6} y={14} style={{ fill: "var(--text-muted)", fontSize: 10 }}>log|σ₂(u)|</text>
      </svg>
      <p className="mono" style={{ fontSize: 13, fontWeight: 700 }}>
        Fundamental unit ε = {eps} ≈ {((u.a + u.b * Math.sqrt(d)) / u.q).toFixed(4)}, norm {u.norm === 1 ? "+1" : "−1"}. Regulator log ε = {R.toFixed(4)}. Units: ±εⁿ for all integers n, a group ℤ/2 × ℤ.
      </p>
      <figcaption className="viz-caption">
        A unit u has |σ₁(u)σ₂(u)| = 1, so its logarithmic image (log|σ₁(u)|, log|σ₂(u)|) lies on the line x + y = 0. The
        images of the units form a lattice in that line, generated by the image of the fundamental unit, whose length
        along each axis is the regulator. Real quadratic fields have r₁ + r₂ − 1 = 1 independent unit.
      </figcaption>
    </figure>
  );
}
