"use client";

import { useState } from "react";

type L = "a" | "A" | "b" | "B";
const SHOW: Record<L, string> = { a: "a", A: "a⁻¹", b: "b", B: "b⁻¹" };
const INV: Record<L, L> = { a: "A", A: "a", b: "B", B: "b" };
const KNOWN: Record<string, string> = {
  "": "nothing attached: π₁ is the free group F(a, b)",
  a: "a dies: π₁ ≅ ℤ, generated by b; the disc fills in the loop a",
  abAB: "π₁ ≅ ℤ², the torus",
  aa: "π₁ ≅ ℤ/2 * ℤ, the projective plane wedged with a circle",
  abaB: "π₁ is the Klein bottle group",
  aaBBB: "π₁ ≅ ⟨a, b | a² = b³⟩, the group of the trefoil knot",
};
const gcd = (x: number, y: number): number => (y === 0 ? Math.abs(x) : gcd(y, x % y));

/** Attaching a 2-cell to a wedge of two circles along a word adds that word as a relation. */
export function CellRelatorViz() {
  const [w, setW] = useState<L[]>(["a", "b", "A", "B"]);
  const push = (l: L) => setW((cur) => (cur.length && cur[cur.length - 1] === INV[l] ? cur.slice(0, -1) : [...cur, l]));
  const key = w.join("");
  const ea = w.filter((l) => l === "a").length - w.filter((l) => l === "A").length;
  const eb = w.filter((l) => l === "b").length - w.filter((l) => l === "B").length;
  const g = gcd(ea, eb);
  const h1 = w.length === 0 ? "ℤ²" : g === 0 ? "ℤ²" : g === 1 ? "ℤ" : `ℤ ⊕ ℤ/${g}`;
  return (
    <figure className="viz">
      <div className="viz-controls">
        {(["a", "A", "b", "B"] as L[]).map((l) => <button key={l} type="button" className="btn btn-ghost" onClick={() => push(l)}>append {SHOW[l]}</button>)}
        <button type="button" className="btn btn-ghost" onClick={() => setW([])}>clear</button>
      </div>
      <div className="segmented" role="group" aria-label="examples" style={{ marginTop: 6 }}>
        {Object.keys(KNOWN).filter((k) => k).map((k) => <button key={k} type="button" aria-pressed={key === k} className={key === k ? "seg is-on" : "seg"} onClick={() => setW(k.split("") as L[])}>{k.split("").map((l) => SHOW[l as L]).join("")}</button>)}
      </div>
      <svg viewBox="0 0 520 90" role="img" aria-label="The boundary word of the attached disc" style={{ width: "100%", display: "block", marginTop: 8 }}>
        {w.length === 0 && <text x={260} y={50} textAnchor="middle" style={{ fill: "var(--text-faint)", fontSize: 13 }}>no 2-cell attached</text>}
        {w.map((l, i) => {
          const W = Math.min(60, 480 / w.length), x = 20 + i * W;
          const col = l.toLowerCase() === "a" ? "var(--accent)" : "var(--success)";
          const fwd = l === l.toLowerCase();
          return (
            <g key={i}>
              <line x1={x + 4} y1={45} x2={x + W - 4} y2={45} style={{ stroke: col, strokeWidth: 4 }} />
              <path d={fwd ? `M${x + W / 2 + 6},45 L${x + W / 2 - 4},39 L${x + W / 2 - 4},51 z` : `M${x + W / 2 - 6},45 L${x + W / 2 + 4},39 L${x + W / 2 + 4},51 z`} style={{ fill: col }} />
              <text x={x + W / 2} y={72} textAnchor="middle" style={{ fill: col, fontSize: 12, fontWeight: 700 }}>{SHOW[l]}</text>
            </g>
          );
        })}
      </svg>
      <p className="mono" style={{ fontSize: 13, fontWeight: 700 }}>
        Relation: {w.length ? w.map((l) => SHOW[l]).join("") + " = 1" : "none"}. {KNOWN[key] ? KNOWN[key][0].toUpperCase() + KNOWN[key].slice(1) + "." : `π₁ ≅ ⟨a, b | ${w.map((l) => SHOW[l]).join("")}⟩.`}
      </p>
      <p className="mono" style={{ fontSize: 13 }}>
        Exponent sums: a {ea}, b {eb}. Abelianising, H₁ ≅ ℤ² modulo ({ea}, {eb}) ≅ {h1}.
      </p>
      <figcaption className="viz-caption">
        Van Kampen applied to a disc attached along a loop: the disc is simply connected, and it meets the rest in an annulus
        around its boundary, so the only new relation is that the boundary word becomes trivial. Every finitely presented
        group arises this way from a 2-complex.
      </figcaption>
    </figure>
  );
}
