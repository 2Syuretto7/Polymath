"use client";

import { useState } from "react";

const isPrime = (n: number) => { if (n < 2) return false; for (let d = 2; d * d <= n; d++) if (n % d === 0) return false; return true; };

/** Whether n = ax² + bxy + cy² for some integers x, y (positive definite forms only). */
export function represents(a: number, b: number, c: number, n: number) {
  for (let x = -40; x <= 40; x++) for (let y = -40; y <= 40; y++) if (a * x * x + b * x * y + c * y * y === n) return true;
  return false;
}

export type Kind = "ramified" | "inert" | "complete" | "split";

/** How a prime p behaves in ℚ(√−5) and its Hilbert class field ℚ(√−5, i). */
export function classify(p: number): Kind {
  if (p === 2 || p === 5) return "ramified";
  if (represents(1, 0, 5, p)) return "complete";
  if (represents(2, 2, 3, p)) return "split";
  return "inert";
}

export const KINDS: { k: Kind; label: string; colour: string; soft: string }[] = [
  { k: "complete", label: "p = x² + 5y²: principal primes, split completely in H", colour: "var(--success)", soft: "var(--success-soft)" },
  { k: "split", label: "p = 2x² + 2xy + 3y²: split in K, non-principal primes", colour: "var(--accent)", soft: "var(--accent-soft)" },
  { k: "inert", label: "inert in K", colour: "var(--danger)", soft: "var(--danger-soft)" },
  { k: "ramified", label: "ramified (2 and 5)", colour: "var(--border-strong)", soft: "var(--bg-subtle)" },
];

/** Primes sorted by their behaviour in K = ℚ(√−5) and its Hilbert class field H = K(i). */
export function PrimeFormViz() {
  const [N, setN] = useState(100);
  const ps = Array.from({ length: N }, (_, i) => i + 1).filter(isPrime);
  const kinds = ps.map(classify);
  const cols = 16, cw = 32, ch = 24;
  const rows = Math.ceil(ps.length / cols);
  const H = 14 + rows * (ch + 4) + KINDS.length * 18 + 10;
  const count = (k: Kind) => kinds.filter((x) => x === k).length;
  return (
    <figure className="viz">
      <div className="viz-controls">
        <label>primes below {N} <input type="range" min={50} max={400} step={50} value={N} onChange={(e) => setN(Number(e.target.value))} aria-label="N" /></label>
      </div>
      <svg viewBox={`0 0 540 ${H}`} role="img" aria-label="Primes coloured by how they split in the Hilbert class field of the field generated by the square root of minus 5" style={{ width: "100%", display: "block", marginTop: 8 }}>
        {ps.map((p, i) => {
          const K = KINDS.find((x) => x.k === kinds[i])!;
          const x = 14 + (i % cols) * cw, y = 6 + Math.floor(i / cols) * (ch + 4);
          return (
            <g key={p}>
              <rect x={x} y={y} width={cw - 4} height={ch} rx={3} style={{ fill: K.soft, stroke: K.colour }} />
              <text x={x + (cw - 4) / 2} y={y + 16} textAnchor="middle" style={{ fill: "var(--text)", fontSize: 10 }}>{p}</text>
            </g>
          );
        })}
        {KINDS.map((K, j) => {
          const y = 14 + rows * (ch + 4) + j * 18;
          return (
            <g key={K.k}>
              <rect x={14} y={y - 9} width={12} height={12} rx={2} style={{ fill: K.soft, stroke: K.colour }} />
              <text x={32} y={y + 1} style={{ fill: "var(--text)", fontSize: 11 }}>{K.label}: {count(K.k)}</text>
            </g>
          );
        })}
      </svg>
      <p className="mono" style={{ fontSize: 13, fontWeight: 700 }}>
        Of the {ps.length - count("ramified")} unramified primes below {N}: {count("complete")} split completely in H, {count("split")} split in K only, {count("inert")} are inert. Chebotarev predicts the proportions 1/4, 1/4, 1/2.
      </p>
      <figcaption className="viz-caption">
        The class group of K = ℚ(√−5) has order 2, and its Hilbert class field is H = K(i). A prime of K is principal exactly
        when it splits completely in H. So a prime p splits completely in H exactly when p = x² + 5y², which happens exactly
        when p ≡ 1 or 9 modulo 20: a congruence condition, as class field theory predicts.
      </figcaption>
    </figure>
  );
}
