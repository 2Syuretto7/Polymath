"use client";

import { useState } from "react";

const PTS = ["a", "b", "c"];
const name = (m: number) => (m === 0 ? "∅" : `{${PTS.filter((_, i) => m & (1 << i)).join(", ")}}`);
const LEVELS = [[7], [3, 5, 6], [1, 2, 4], [0]]; // by size, largest at the top
const PRESETS = [
  { label: "indiscrete", s: [0, 7] },
  { label: "discrete", s: [0, 1, 2, 3, 4, 5, 6, 7] },
  { label: "a chain", s: [0, 1, 3, 7] },
  { label: "not a topology", s: [0, 1, 2, 7] },
];

function check(s: Set<number>): string | null {
  if (!s.has(0)) return "∅ is missing";
  if (!s.has(7)) return "the whole set X = {a, b, c} is missing";
  for (const u of s) for (const v of s) {
    if (!s.has(u | v)) return `${name(u)} ∪ ${name(v)} = ${name(u | v)} is missing`;
    if (!s.has(u & v)) return `${name(u)} ∩ ${name(v)} = ${name(u & v)} is missing`;
  }
  return null;
}
function generate(s: Set<number>): Set<number> {
  const t = new Set([...s, 0, 7]);
  let grew = true;
  while (grew) {
    grew = false;
    for (const u of [...t]) for (const v of [...t]) for (const w of [u | v, u & v]) if (!t.has(w)) { t.add(w); grew = true; }
  }
  return t;
}

/** Topologies on a three-point set: choose which subsets are open and test the axioms. */
export function FiniteTopologyViz() {
  const [s, setS] = useState(new Set([0, 1, 2, 7]));
  const err = check(s);
  const toggle = (m: number) => { const t = new Set(s); if (t.has(m)) t.delete(m); else t.add(m); setS(t); };
  return (
    <figure className="viz">
      <div className="segmented" role="group" aria-label="Preset">
        {PRESETS.map((p) => {
          const on = p.s.length === s.size && p.s.every((x) => s.has(x));
          return <button key={p.label} type="button" aria-pressed={on} className={on ? "seg is-on" : "seg"} onClick={() => setS(new Set(p.s))}>{p.label}</button>;
        })}
      </div>
      <p style={{ margin: "10px 0 6px", fontSize: 14 }}>Click a subset of X = {"{a, b, c}"} to declare it open or not.</p>
      <div style={{ display: "grid", gap: 8, justifyItems: "center" }}>
        {LEVELS.map((lv, i) => (
          <div key={i} style={{ display: "flex", gap: 8, flexWrap: "wrap", justifyContent: "center" }}>
            {lv.map((m) => (
              <button key={m} type="button" aria-pressed={s.has(m)} className={s.has(m) ? "btn btn-primary" : "btn"} style={{ minWidth: 86 }} onClick={() => toggle(m)}>{name(m)}</button>
            ))}
          </div>
        ))}
      </div>
      <div className="viz-controls" style={{ marginTop: 10 }}>
        <button type="button" className="btn" disabled={!err} onClick={() => setS(generate(s))}>Add what is needed</button>
      </div>
      <div className="mono" style={{ display: "grid", gap: 4, fontSize: 14, marginTop: 6 }}>
        <div>open sets: {[...s].sort((x, y) => x - y).map(name).join(", ")}</div>
        <div>a topology: <strong>{err ? `no, ${err}` : "yes"}</strong></div>
      </div>
      <figcaption className="viz-caption">
        A topology must contain ∅ and X and be closed under unions and finite intersections. The button adds the fewest sets
        needed, giving the topology generated by your choice. There are 29 different topologies on a three-point set.
      </figcaption>
    </figure>
  );
}
