"use client";

import { useState } from "react";

type Root = { label: string; z: [number, number] };
type Poly = { name: string; roots: Root[]; gens: string[]; field: (s: boolean[]) => { has: boolean[]; deg: number }; full: number };

const c2 = Math.cbrt(2), q2 = Math.pow(2, 0.25), w: [number, number] = [-0.5, Math.sqrt(3) / 2];
const POLYS: Poly[] = [
  {
    name: "x³ − 2",
    roots: [
      { label: "∛2", z: [c2, 0] },
      { label: "ω∛2", z: [c2 * w[0], c2 * w[1]] },
      { label: "ω²∛2", z: [c2 * w[0], -c2 * w[1]] },
    ],
    gens: ["∛2", "ω∛2", "ω"],
    field: ([a, b, om]) => {
      const R = [a, b].filter(Boolean).length;
      if (R === 2 || (R === 1 && om)) return { has: [true, true, true], deg: 6 };
      if (R === 1) return { has: [a, b, false], deg: 3 };
      return { has: [false, false, false], deg: om ? 2 : 1 };
    },
    full: 6,
  },
  {
    name: "x⁴ − 2",
    roots: [
      { label: "⁴√2", z: [q2, 0] },
      { label: "−⁴√2", z: [-q2, 0] },
      { label: "i⁴√2", z: [0, q2] },
      { label: "−i⁴√2", z: [0, -q2] },
    ],
    gens: ["⁴√2", "i⁴√2", "i"],
    field: ([a, b, i]) => {
      const n = [a, b, i].filter(Boolean).length;
      if (n >= 2) return { has: [true, true, true, true], deg: 8 };
      if (a) return { has: [true, true, false, false], deg: 4 };
      if (b) return { has: [false, false, true, true], deg: 4 };
      return { has: [false, false, false, false], deg: i ? 2 : 1 };
    },
    full: 8,
  },
  {
    name: "(x² − 2)(x² − 3)",
    roots: [
      { label: "√2", z: [Math.SQRT2, 0] },
      { label: "−√2", z: [-Math.SQRT2, 0] },
      { label: "√3", z: [Math.sqrt(3), -0.0001] },
      { label: "−√3", z: [-Math.sqrt(3), -0.0001] },
    ],
    gens: ["√2", "√3", "√6"],
    field: ([a, b, c]) => {
      const n = [a, b, c].filter(Boolean).length;
      if (n >= 2) return { has: [true, true, true, true], deg: 4 };
      if (a) return { has: [true, true, false, false], deg: 2 };
      if (b) return { has: [false, false, true, true], deg: 2 };
      return { has: [false, false, false, false], deg: c ? 2 : 1 };
    },
    full: 4,
  },
];

/** Splitting fields: adjoin numbers to ℚ and see which roots of the polynomial the field contains. */
export function SplitFieldViz() {
  const [pi, setPi] = useState(0);
  const [sel, setSel] = useState([true, false, false]);
  const P = POLYS[pi];
  const { has, deg } = P.field(sel);
  const splits = has.every(Boolean);
  const W = 300, B = 2.2, X = (x: number) => W / 2 + (x / B) * (W / 2 - 10), Y = (y: number) => W / 2 - (y / B) * (W / 2 - 10);
  const chosen = P.gens.filter((_, i) => sel[i]);
  return (
    <figure className="viz">
      <div className="segmented" role="group" aria-label="Polynomial">
        {POLYS.map((p, i) => <button key={p.name} type="button" aria-pressed={pi === i} className={pi === i ? "seg is-on" : "seg"} onClick={() => { setPi(i); setSel([true, false, false]); }}>{p.name}</button>)}
      </div>
      <div className="viz-controls" style={{ marginTop: 8 }}>
        <span style={{ fontSize: 14 }}>adjoin:</span>
        {P.gens.map((g, i) => <button key={g} type="button" aria-pressed={sel[i]} className={sel[i] ? "viz-chip is-on" : "viz-chip"} onClick={() => setSel(sel.map((s, j) => (j === i ? !s : s)))}>{g}</button>)}
      </div>
      <svg viewBox={`0 0 ${W} ${W}`} role="img" aria-label="Roots of the polynomial in the complex plane" style={{ width: "100%", maxWidth: 320, display: "block", margin: "6px auto" }}>
        <line x1={0} y1={Y(0)} x2={W} y2={Y(0)} style={{ stroke: "var(--border)" }} />
        <line x1={X(0)} y1={0} x2={X(0)} y2={W} style={{ stroke: "var(--border)" }} />
        {P.roots.map((r, i) => (
          <g key={r.label}>
            <circle cx={X(r.z[0])} cy={Y(r.z[1])} r={8} style={{ fill: has[i] ? "var(--accent)" : "var(--bg)", stroke: "var(--accent)", strokeWidth: 2 }} />
            <text x={X(r.z[0])} y={Y(r.z[1]) + (r.z[1] < 0 ? 24 : -14)} textAnchor="middle" style={{ fill: "var(--text)", fontSize: 13 }}>{r.label}</text>
          </g>
        ))}
      </svg>
      <div className="mono" style={{ display: "grid", gap: 4, fontSize: 14 }}>
        <div>field: {chosen.length ? `ℚ(${chosen.join(", ")})` : "ℚ"}; degree over ℚ: {deg}</div>
        <div>roots in this field: {has.filter(Boolean).length} of {P.roots.length}; {splits ? `the polynomial splits: this is the splitting field, of degree ${P.full}` : "the polynomial does not split here"}</div>
      </div>
      <figcaption className="viz-caption">
        Filled circles are roots that lie in the field generated by the chosen numbers. The splitting field is the smallest
        field containing every root. For x³ − 2, the real field ℚ(∛2) holds only one root, and adjoining ω as well gives
        degree 6.
      </figcaption>
    </figure>
  );
}
